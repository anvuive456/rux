import java.util.Properties

plugins {
    id("com.android.application")
}

// Application id (`app-id` in [package.metadata.rux]) and version name / code
// (`version = "x.y.z+n"`) come from the app's Cargo.toml; `rux build android` writes
// them to ../rux.properties.
val ruxProperties = Properties().apply {
    val file = rootProject.file("rux.properties")
    if (!file.exists()) {
        throw GradleException("${file.path} not found: run `rux build android` first.")
    }
    file.inputStream().use { load(it) }
}

android {
    // Kotlin/R package of the app's code — independent of applicationId.
    namespace = "{{android_package}}"
    compileSdk = 35

    defaultConfig {
        applicationId = ruxProperties.getProperty("rux.applicationId")
        minSdk = 24
        targetSdk = 35
        versionCode = ruxProperties.getProperty("rux.versionCode").toInt()
        versionName = ruxProperties.getProperty("rux.versionName")

        ndk {
            // Must match the ABIs built with `rux build android --abi ...`.
            abiFilters += listOf("arm64-v8a", "x86_64")
        }
    }

    // `rux build android` copies lib{{lib_name}}.so into src/debug/jniLibs/<abi>/, and
    // `rux build android --release` into src/release/jniLibs/<abi>/ (checked below).

    // Native APIs (#[rux::host_api]): code generated by `rux build android` + plugin sources.
    sourceSets.getByName("main").kotlin.srcDirs(
        ruxProperties.getProperty("rux.sourceDirs", "").split(',').filter { it.isNotBlank() },
    )

    buildTypes {
        release {
            // R8: shrinks and obfuscates the Kotlin / Java code. rux-runtime ships the keep
            // rules for what Rust calls over JNI (consumer-rules.pro).
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"))
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}


dependencies {
    implementation(project(":rux-runtime"))
}

// The Rust library is built per build type: fail early instead of packaging an APK / bundle
// without it (or, as before, with the debug build in a release).
tasks.matching { it.name.matches(Regex("merge(Debug|Release)JniLibFolders")) }.configureEach {
    val buildType = name.removePrefix("merge").removeSuffix("JniLibFolders").lowercase()
    val jniLibs = file("src/$buildType/jniLibs")
    val command = if (buildType == "release") "rux build android --release" else "rux build android"
    doFirst {
        if (!jniLibs.isDirectory) {
            throw GradleException("${jniLibs.path} not found: run `$command` first.")
        }
    }
}