//! `rux build ios`: writes `rux.xcconfig` (bundle id, version, signing team) and builds `lib<name>.a` for device + simulator into an xcframework.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

use crate::Platform;
use crate::app::AppCrate;
use crate::deps::Deps;
use crate::util::{cargo_out_dir, run, write_generated};

const TARGETS: [&str; 2] = ["aarch64-apple-ios", "aarch64-apple-ios-sim"];

pub fn build(app: &AppCrate, release: bool) -> Result<Option<PathBuf>> {
    let deps = Deps::for_build(app, Platform::Ios, &TARGETS)?;
    if !cfg!(target_os = "macos") {
        bail!("building for iOS requires macOS + Xcode");
    }
    let mut project = app.meta.ios_project.as_ref().map(|p| app.dir.join(p));
    let generated = project.is_none() && app.generates_native_projects();
    let profile = if release { "release" } else { "debug" };
    let target_dir = app.target_dir()?;
    let lib_file = format!("lib{}.a", app.lib_name);

    for t in TARGETS {
        let mut cmd = Command::new("cargo");
        cmd.current_dir(&app.dir)
            .args(["build", "-p", &app.package, "--lib", "--target", t]);
        cmd.args(app.cargo_args(Platform::Ios));
        if release {
            cmd.arg("--release");
        }
        if generated && project.is_none() {
            let out = cargo_out_dir(&mut cmd, &app.dir.join("Cargo.toml"))?;
            let native = out.join("ios");
            anyhow::ensure!(
                native.join("project.yml").is_file(),
                "iOS project was not generated in {}",
                out.display()
            );
            project = Some(native);
        } else {
            run(&mut cmd)?;
        }
    }

    if let Some(project) = &project {
        write_config(project, app)?;
        write_project_include(project, &deps.ios_runtime()?)?;
        crate::native::generate_ios(&deps, project)?;
    }
    let output_dir = if generated {
        project
            .as_ref()
            .context("missing generated iOS project")?
            .clone()
    } else {
        target_dir.join("ios")
    };
    let out = output_dir.join(format!("{}.xcframework", app.lib_name));
    if out.exists() {
        std::fs::remove_dir_all(&out)?;
    }
    let mut cmd = Command::new("xcodebuild");
    cmd.arg("-create-xcframework");
    for t in TARGETS {
        cmd.arg("-library")
            .arg(target_dir.join(t).join(profile).join(&lib_file));
    }
    cmd.arg("-output").arg(&out);
    run(&mut cmd)?;
    // Which profile the xcframework holds: the Xcode project's pre-build check compares it
    // with the configuration being built, so a Release build never links the debug library.
    write_generated(&profile_marker(&out), &format!("{profile}\n"))?;

    println!("→ {}", out.display());
    if let Some(project) = &project {
        println!(
            "  open the project: cd {} && xcodegen && open *.xcodeproj",
            project.display()
        );
    }
    Ok(project)
}

/// `<name>.profile` next to `<name>.xcframework`: `debug` or `release`.
fn profile_marker(xcframework: &Path) -> std::path::PathBuf {
    xcframework.with_extension("profile")
}

/// Writes `<ios>/rux.yml`, included by `project.yml`: the rux runtime Swift package, taken from
/// the `rux` crate cargo resolved for the app.
fn write_project_include(project: &Path, runtime: &Path) -> Result<()> {
    let path = runtime
        .to_string_lossy()
        .replace('\\', "\\\\")
        .replace('"', "\\\"");
    write_generated(
        &project.join("rux.yml"),
        &format!(
            "# Generated by `rux build ios` from Cargo.toml — do not edit.\n\
             packages:\n  RuxRuntime:\n    path: \"{path}\"\n"
        ),
    )
}

/// Writes `<ios>/rux.xcconfig` (bundle id + version), referenced by `project.yml` (`configFiles`).
fn write_config(project: &Path, app: &AppCrate) -> Result<()> {
    let bundle_id = app.meta.ios_bundle_id()?;
    let v = &app.version;
    let mut body = format!(
        "// Generated by `rux build ios` from Cargo.toml — do not edit.\n\
         PRODUCT_BUNDLE_IDENTIFIER = {bundle_id}\n\
         MARKETING_VERSION = {}\nCURRENT_PROJECT_VERSION = {}\n",
        v.name, v.code
    );
    if let Some(team) = &app.meta.ios_development_team {
        body += &format!("DEVELOPMENT_TEAM = {team}\n");
    }
    write_generated(&project.join("rux.xcconfig"), &body)
}
