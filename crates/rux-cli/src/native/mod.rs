//! Native APIs (`#[rux::host_api]`): generates the Kotlin / Swift side for the app and every
//! plugin it depends on, plus the registrant that wires their implementations up at startup.
//!
//! A crate takes part through its `Cargo.toml`:
//!
//! ```toml
//! # Implementation class of each API, per platform (Android constructor: `(Context)`,
//! # iOS: `init()`).
//! [package.metadata.rux.native]
//! DeviceInfoApi = { android = "dev.rux.plugins.deviceinfo.DeviceInfoApiImpl", ios = "DeviceInfoApiImpl" }
//!
//! # Plugins only: where their native implementation sources live (relative to the crate).
//! [package.metadata.rux.plugin]
//! android = "android"
//! ios = "ios"
//! ```
//!
//! Output (gitignored, rewritten on every `rux build`):
//! - Android: `<android>/rux-generated/kotlin/` — added to the app's sources (with plugin
//!   sources) through `rux.sourceDirs` in `rux.properties`;
//! - iOS: `<ios>/rux-generated/` (generated code + copies of plugin sources) — a source
//!   folder of the XcodeGen project.

mod kotlin;
mod naming;
mod schema;
mod swift;

use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde_json::Value;

use crate::app::AppCrate;
use schema::Schema;

const HEADER: &str = "Generated by `rux build` from #[rux::host_api] declarations. Do not edit.";
const OUT_DIR: &str = "rux-generated";

/// Implementation classes of one API.
#[derive(Debug, Default)]
pub struct Impl {
    pub android: Option<String>,
    pub ios: Option<String>,
}

/// A crate (the app or a plugin) with native APIs.
pub struct NativePackage {
    pub name: String,
    pub schema: Schema,
    pub impls: BTreeMap<String, Impl>,
    pub android_sources: Option<PathBuf>,
    pub ios_sources: Option<PathBuf>,
}

/// Generates the Kotlin side into `<project>/rux-generated/kotlin`. Returns the source
/// directories to add to the app module (generated code + plugin sources).
pub fn generate_android(app: &AppCrate, project: &Path) -> Result<Vec<PathBuf>> {
    let packages = collect(app)?;
    let out = project.join(OUT_DIR).join("kotlin");
    reset_dir(&project.join(OUT_DIR))?;
    if packages.is_empty() {
        return Ok(Vec::new());
    }
    let base = out.join("dev/rux/generated");
    for pkg in packages.iter().filter(|p| !p.schema.is_empty()) {
        let dir = base.join(pkg.name.replace('-', "_"));
        write(
            &dir.join("NativeApis.kt"),
            &kotlin::file(&pkg.name, &pkg.schema),
        )?;
    }
    write(
        &base.join("RuxRegistrant.kt"),
        &kotlin::registrant(&packages),
    )?;
    report(&packages, "Android");

    let mut dirs = vec![out];
    dirs.extend(packages.iter().filter_map(|p| p.android_sources.clone()));
    Ok(dirs)
}

/// Generates the Swift side (and copies plugin sources) into `<project>/rux-generated`.
pub fn generate_ios(app: &AppCrate, project: &Path) -> Result<()> {
    let packages = collect(app)?;
    let out = project.join(OUT_DIR);
    reset_dir(&out)?;
    if packages.is_empty() {
        return Ok(());
    }
    for pkg in &packages {
        let name = pkg.name.replace('-', "_");
        if !pkg.schema.is_empty() {
            write(
                &out.join(format!("{name}.swift")),
                &swift::file(&pkg.name, &pkg.schema),
            )?;
        }
        if let Some(src) = &pkg.ios_sources {
            copy_sources(src, &out.join("plugins").join(&name), "swift")?;
        }
    }
    write(
        &out.join("RuxRegistrant.swift"),
        &swift::registrant(&packages),
    )?;
    report(&packages, "iOS");
    Ok(())
}

/// `(package, api, implementation class)` for every API implemented on a platform; warns
/// about the others (calling them fails with `not_implemented`).
fn implementations<'a>(
    packages: &'a [NativePackage],
    platform: impl Fn(&'a Impl) -> Option<&'a str>,
) -> Vec<(&'a NativePackage, &'a str, &'a str)> {
    let mut out = Vec::new();
    for pkg in packages {
        for api in &pkg.schema.apis {
            match pkg.impls.get(&api.name).and_then(&platform) {
                Some(imp) => out.push((pkg, api.name.as_str(), imp)),
                None => println!(
                    "   warning: no implementation of {}.{} for this platform in \
                     [package.metadata.rux.native]: calls will fail with `not_implemented`",
                    pkg.name, api.name
                ),
            }
        }
    }
    out
}

fn report(packages: &[NativePackage], platform: &str) {
    let apis: Vec<String> = packages
        .iter()
        .flat_map(|p| {
            p.schema
                .apis
                .iter()
                .map(move |a| format!("{} ({})", a.name, p.name))
        })
        .collect();
    println!("→ generated {platform} native APIs: {}", apis.join(", "));
}

/// The app and its dependencies that declare native APIs, in dependency-name order.
fn collect(app: &AppCrate) -> Result<Vec<NativePackage>> {
    let out = Command::new("cargo")
        .args(["metadata", "--format-version=1"])
        .current_dir(&app.dir)
        .output()
        .context("running cargo metadata")?;
    if !out.status.success() {
        bail!(
            "cargo metadata failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    let meta: Value = serde_json::from_slice(&out.stdout).context("parsing cargo metadata")?;
    let packages = meta["packages"].as_array().context("no packages")?;

    let manifest = std::fs::canonicalize(app.dir.join("Cargo.toml"))?;
    let app_id = packages
        .iter()
        .find(|p| {
            p["manifest_path"]
                .as_str()
                .and_then(|m| std::fs::canonicalize(m).ok())
                .is_some_and(|m| m == manifest)
        })
        .and_then(|p| p["id"].as_str())
        .context("app package not found in cargo metadata")?;

    // The app's dependency closure.
    let nodes: BTreeMap<&str, Vec<&str>> = meta["resolve"]["nodes"]
        .as_array()
        .context("no dependency graph")?
        .iter()
        .filter_map(|n| {
            let deps = n["deps"]
                .as_array()?
                .iter()
                .filter_map(|d| d["pkg"].as_str())
                .collect();
            Some((n["id"].as_str()?, deps))
        })
        .collect();
    let mut seen = BTreeSet::from([app_id]);
    let mut queue = VecDeque::from([app_id]);
    while let Some(id) = queue.pop_front() {
        for &dep in nodes.get(id).into_iter().flatten() {
            if seen.insert(dep) {
                queue.push_back(dep);
            }
        }
    }

    let mut found = Vec::new();
    for pkg in packages {
        if !pkg["id"].as_str().is_some_and(|id| seen.contains(id)) {
            continue;
        }
        let rux = &pkg["metadata"]["rux"];
        let (native, plugin) = (&rux["native"], &rux["plugin"]);
        if native.is_null() && plugin.is_null() {
            continue;
        }
        let name = pkg["name"].as_str().unwrap_or_default().to_owned();
        let dir = Path::new(pkg["manifest_path"].as_str().unwrap_or_default())
            .parent()
            .context("package directory")?
            .to_path_buf();
        found.push(
            read_package(name.clone(), &dir, native, plugin)
                .with_context(|| format!("native APIs of `{name}`"))?,
        );
    }
    found.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(found)
}

fn read_package(name: String, dir: &Path, native: &Value, plugin: &Value) -> Result<NativePackage> {
    let schema = schema::read(&dir.join("src"))?;
    let mut impls = BTreeMap::new();
    if let Some(table) = native.as_object() {
        for (api, imp) in table {
            if !schema.apis.iter().any(|a| &a.name == api) {
                bail!(
                    "[package.metadata.rux.native] names `{api}`, which is not a #[host_api] trait"
                );
            }
            let get = |k: &str| imp[k].as_str().map(str::to_owned);
            impls.insert(
                api.clone(),
                Impl {
                    android: get("android"),
                    ios: get("ios"),
                },
            );
        }
    }
    let source = |key: &str| -> Result<Option<PathBuf>> {
        match plugin[key].as_str() {
            None => Ok(None),
            Some(rel) => {
                let path = dir.join(rel);
                if !path.is_dir() {
                    bail!("[package.metadata.rux.plugin] {key} = \"{rel}\": no such directory");
                }
                Ok(Some(path))
            }
        }
    };
    Ok(NativePackage {
        name,
        schema,
        impls,
        android_sources: source("android")?,
        ios_sources: source("ios")?,
    })
}

fn reset_dir(dir: &Path) -> Result<()> {
    if dir.exists() {
        std::fs::remove_dir_all(dir).with_context(|| format!("removing {}", dir.display()))?;
    }
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))
}

fn write(path: &Path, contents: &str) -> Result<()> {
    std::fs::create_dir_all(path.parent().unwrap())?;
    std::fs::write(path, contents).with_context(|| format!("writing {}", path.display()))
}

/// Copies the `*.<ext>` files under `from` (recursively) into `to`.
fn copy_sources(from: &Path, to: &Path, ext: &str) -> Result<()> {
    for entry in std::fs::read_dir(from).with_context(|| format!("reading {}", from.display()))? {
        let path = entry?.path();
        let target = to.join(path.file_name().unwrap());
        if path.is_dir() {
            copy_sources(&path, &target, ext)?;
        } else if path.extension().is_some_and(|e| e == ext) {
            std::fs::create_dir_all(to)?;
            std::fs::copy(&path, &target).with_context(|| format!("copying {}", path.display()))?;
        }
    }
    Ok(())
}
